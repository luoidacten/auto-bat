// Capture base skill geometry with the real, DOM-free engine. No simulation is
// run on the phone to calculate previews; build ships this small lookup table.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import {
  ArenaSession,
  ENGINE_VERSION,
  ROSTER,
  withRandom,
} from "../engine/runtime.mjs";

const positive = (n, fallback) =>
  Number.isFinite(n) && n > 0 ? Math.min(2000, n) : fallback;
const guides = {};
for (const hero of ROSTER) {
  guides[hero.id] = {};
  const keys = Object.keys(
    new ArenaSession({
      mode: "training",
      heroes: [hero.id, "zero"],
    }).match.lead(0).weapon.skills,
  );
  for (const key of keys) {
    const session = new ArenaSession({
      mode: "training",
      heroes: [hero.id, "zero"],
      seed: "skill-guide-" + hero.id + key,
    });
    const match = session.match,
      fighter = match.lead(0),
      target = match.lead(1);
    const skill = fighter.weapon.skills[key],
      events = [];
    match.state = "fight";
    fighter.x = fighter.y = fighter.facing = fighter.castAngle = 0;
    fighter.rage = 1000;
    target.x = Math.min(300, positive(skill.ai?.max, 100));
    target.y = 0;
    target.invulnT = 1000;
    const add = (shape, opts) => events.push({ shape, ...opts });
    const offset = (x = fighter.x, y = fighter.y) => Math.hypot(x, y);
    for (const [method, shape] of [
      ["hitArc", "cone"],
      ["hitLine", "line"],
      ["hitCircle", "circle"],
    ]) {
      const original = match[method];
      match[method] = function (owner, options) {
        if (owner === fighter && (!options.tag || options.tag === key))
          add(shape, {
            range: positive(options.range ?? options.len ?? options.r, 80),
            width: positive(options.w, 24),
            arc: positive(options.arc, 110),
            offset: offset(options.x, options.y),
          });
        return original.call(this, owner, options);
      };
    }
    const projectile = match.proj;
    match.proj = function (options) {
      if (
        options.owner === fighter &&
        (!options.hit?.tag || options.hit.tag === key)
      )
        add("line", {
          range: positive(options.range, 500) + offset(options.x, options.y),
          width: positive(options.r, 7) * 2,
          angle: options.angle || 0,
          projectile: true,
          offset: 0,
        });
      return projectile.call(this, options);
    };
    const zone = match.zone;
    match.zone = function (options) {
      if (options.owner === fighter)
        add("circle", {
          range: positive(options.r, 50),
          offset: offset(options.x, options.y),
        });
      return zone.call(this, options);
    };
    const dash = fighter.startDash;
    fighter.startDash = function (options) {
      add("dash", {
        range: positive(options.dist, 90),
        width: fighter.r * 2,
        offset: 0,
      });
      return dash.call(this, options);
    };
    try {
      fighter.manualHold = skill.hold || 0.05;
      fighter.intent = { hold: false };
      withRandom(session.rng, () => fighter.tryUse(key, match));
      for (let i = 0; i < 150; i++) session.step();
    } catch (error) {
      throw new Error(hero.id + " " + key + " preview: " + error.message);
    }
    const first = events.find((e) => e.shape !== "dash") || events[0];
    let guide;
    if (first) {
      if (first.shape === "circle")
        guide =
          first.offset > 30
            ? { shape: "area", range: first.offset, radius: first.range }
            : { shape: "circle", range: first.range };
      else
        guide = {
          shape: first.shape,
          range: first.range + first.offset,
          ...(first.shape === "cone"
            ? { arc: first.arc }
            : { width: first.width }),
        };
      const shots = events.filter((e) => e.projectile);
      if (first.projectile && shots.length > 1) {
        const spread = shots.map((e) =>
          Math.atan2(
            Math.sin(e.angle - first.angle),
            Math.cos(e.angle - first.angle),
          ),
        );
        const arc =
          ((Math.max(...spread) - Math.min(...spread)) * 180) / Math.PI;
        if (arc > 5 && arc < 180)
          guide = { shape: "cone", range: first.range, arc: arc + 4 };
      }
    } else if (["buff", "def"].includes(skill.ai?.type))
      guide = { shape: "circle", range: fighter.r + 24 };
    else
      guide = {
        shape: "line",
        range: positive(skill.ai?.max, positive(fighter.weapon.ai?.range, 150)),
        width: 24,
        estimated: true,
      };
    guides[hero.id][key] = Object.fromEntries(
      Object.entries(guide).map(([k, v]) => [
        k,
        typeof v === "number" ? Math.round(v * 10) / 10 : v,
      ]),
    );
  }
}
const output =
  "// Generated by tools/skill-guides.mjs from base casts; edit engine skill definitions.\n" +
  "export const GUIDE_VERSION = " +
  JSON.stringify(ENGINE_VERSION) +
  ";\n" +
  "export const SKILL_GUIDES = " +
  JSON.stringify(guides, null, 2) +
  ";\n";
fs.writeFileSync(
  fileURLToPath(new URL("../client/skill-guides.mjs", import.meta.url)),
  output,
);
